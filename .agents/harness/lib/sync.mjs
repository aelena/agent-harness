// `harness sync`: everything agent-specific is generated from one source.
//
//   .agents/skills, .agents/agents, AGENTS.md, .agents/harness.json   (you edit)
//        │
//        ▼
//   CLAUDE.md, .claude/settings.json, .claude/skills, .cursor/hooks.json,
//   .github/hooks/harness.json, .codex/hooks.json, plugin manifests, README tables
//
// `planSync` computes the desired output, `diffSync` reports drift (used by
// `check` and CI), `applySync` writes it. Hand edits to generated output are
// overwritten, and files the harness does not own are merged, never replaced.

import { cpSync, existsSync, lstatSync, mkdirSync, readdirSync, realpathSync, rmSync, symlinkSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { parseFrontmatter } from './frontmatter.mjs';
import { matchAny } from './glob.mjs';
import { isDir, loadConfig, read, walk } from './util.mjs';

export const KNOWN_AGENTS = ['claude', 'cursor', 'copilot', 'codex', 'gemini', 'opencode'];
const MARKER = '.harness-generated';
const GENERATED_NOTE = 'Generated by `harness sync`. Edit AGENTS.md instead.';
const hookPath = (name) => `.agents/harness/hooks/${name}.mjs`;
const isOurs = (entry) => JSON.stringify(entry).includes('harness/hooks/');
const json = (obj) => `${JSON.stringify(obj, null, 2)}\n`;

function readJson(file, notes) {
  if (!existsSync(file)) return {};
  try {
    return JSON.parse(read(file));
  } catch (e) {
    notes.push(`${file}: not valid JSON (${e.message}); it will be rewritten.`);
    return {};
  }
}

/** Replace our entries in an event → entries map, keep everyone else's. */
function mergeHooks(existing = {}, ours = {}) {
  const merged = {};
  for (const event of new Set([...Object.keys(existing), ...Object.keys(ours)])) {
    const kept = (existing[event] ?? []).filter((e) => !isOurs(e));
    const list = [...kept, ...(ours[event] ?? [])];
    if (list.length) merged[event] = list;
  }
  return merged;
}

// ------------------------------------------------------------------ per-agent hook wiring

function claudeHooks(config, base = '${CLAUDE_PROJECT_DIR}') {
  const h = (name, timeout) => ({ type: 'command', command: 'node', args: [`${base}/${hookPath(name)}`, '--agent', 'claude'], timeout });
  const hooks = {
    PreToolUse: [{ matcher: 'Bash|PowerShell|Read|Grep|Edit|Write|MultiEdit|NotebookEdit', hooks: [h('guard', 10)] }],
    SessionStart: [{ hooks: [h('session-start', 20)] }],
  };
  if (config.sensors.postEdit?.length) hooks.PostToolUse = [{ matcher: 'Edit|Write|MultiEdit|NotebookEdit', hooks: [h('feedback', 90)] }];
  if (config.sensors.verify) hooks.Stop = [{ hooks: [h('stop-gate', config.sensors.verifyTimeoutSec + 30)] }];
  return hooks;
}

function cursorHooks(config) {
  const cmd = (name) => `node ${hookPath(name)} --agent cursor`;
  const hooks = {
    beforeShellExecution: [{ command: cmd('guard'), timeout: 10 }],
    beforeReadFile: [{ command: cmd('guard'), timeout: 10 }],
    preToolUse: [{ command: cmd('guard'), matcher: 'Write|Delete', timeout: 10 }],
    sessionStart: [{ command: cmd('session-start'), timeout: 20 }],
  };
  if (config.sensors.postEdit?.length) hooks.postToolUse = [{ command: cmd('feedback'), matcher: 'Write', timeout: 90 }];
  if (config.sensors.verify) hooks.stop = [{ command: cmd('stop-gate'), timeout: config.sensors.verifyTimeoutSec + 30, loop_limit: config.sensors.maxStopBlocks }];
  return hooks;
}

function copilotHooks(config) {
  const h = (name, timeoutSec) => ({ type: 'command', command: `node ${hookPath(name)} --agent copilot`, timeoutSec });
  const hooks = { preToolUse: [h('guard', 10)], sessionStart: [h('session-start', 20)] };
  if (config.sensors.postEdit?.length) hooks.postToolUse = [h('feedback', 90)];
  if (config.sensors.verify) hooks.agentStop = [h('stop-gate', config.sensors.verifyTimeoutSec + 30)];
  return hooks;
}

function codexHooks(config) {
  // Codex runs hooks from the session cwd, so the path is resolved from the git root.
  const h = (name, timeout) => ({ type: 'command', command: `node "$(git rev-parse --show-toplevel)/${hookPath(name)}" --agent codex`, timeout });
  const hooks = {
    PreToolUse: [{ matcher: 'Bash|apply_patch|Edit|Write', hooks: [h('guard', 10)] }],
    SessionStart: [{ hooks: [h('session-start', 20)] }],
  };
  if (config.sensors.postEdit?.length) hooks.PostToolUse = [{ matcher: 'apply_patch|Edit|Write', hooks: [h('feedback', 90)] }];
  if (config.sensors.verify) hooks.Stop = [{ hooks: [h('stop-gate', config.sensors.verifyTimeoutSec + 30)] }];
  return hooks;
}

function geminiHooks(config) {
  const h = (name, seconds) => ({ name: `harness-${name}`, type: 'command', command: `node ${hookPath(name)} --agent gemini`, timeout: seconds * 1000 });
  const hooks = {
    BeforeTool: [{ matcher: 'run_shell_command|read_file|read_many_files|write_file|replace', hooks: [h('guard', 10)] }],
    SessionStart: [{ hooks: [h('session-start', 20)] }],
  };
  if (config.sensors.postEdit?.length) hooks.AfterTool = [{ matcher: 'write_file|replace', hooks: [h('feedback', 90)] }];
  if (config.sensors.verify) hooks.AfterAgent = [{ hooks: [h('stop-gate', config.sensors.verifyTimeoutSec + 30)] }];
  return hooks;
}

const OPENCODE_PLUGIN = `// Generated by \`harness sync\`. Do not edit: change .agents/harness.json instead.
//
// OpenCode runs plugins in-process, so this calls the policy directly instead
// of spawning the guard hook. A thrown error blocks the tool call and its
// message is what the model reads.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { normalize } from '../../.agents/harness/lib/dialects.mjs';
import { evaluate, mergePolicy } from '../../.agents/harness/lib/policy.mjs';

function policyFor(dir) {
  try {
    return mergePolicy(JSON.parse(readFileSync(join(dir, '.agents', 'harness.json'), 'utf8')).policy);
  } catch {
    return mergePolicy();
  }
}

function check(tool, input, dir) {
  const verdict = evaluate(normalize({ tool_name: tool, tool_input: input ?? {} }), policyFor(dir));
  if (verdict.decision === 'deny') throw new Error(verdict.reason);
  if (verdict.decision === 'ask') throw new Error(\`\${verdict.reason} Ask the user to approve it or to run it themselves.\`);
}

export default {
  id: 'agent-harness.guard',
  // OpenCode V2
  async setup(ctx) {
    await ctx.tool.hook('execute.before', (event) => check(event.tool, event.input, ctx.location?.directory ?? process.cwd()));
  },
  // OpenCode V1 (1.18.29 and newer accept an object entrypoint)
  async server(input) {
    return { 'tool.execute.before': async (call, output) => check(call.tool, output?.args, input?.directory ?? process.cwd()) };
  },
};
`;

// ------------------------------------------------------------------ generated documents

export function loadSkillMeta(root) {
  const base = join(root, '.agents', 'skills');
  if (!isDir(base)) return [];
  return readdirSync(base, { withFileTypes: true })
    .filter((e) => e.isDirectory() && existsSync(join(base, e.name, 'SKILL.md')))
    .map((e) => ({ name: e.name, ...parseFrontmatter(read(join(base, e.name, 'SKILL.md'))).data }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

function groupsOf(skills, config) {
  const declared = Object.keys(config.groups ?? {});
  const ids = [...new Set(skills.map((s) => s.metadata?.group ?? 'other'))].sort((a, b) => {
    const [ia, ib] = [declared.indexOf(a), declared.indexOf(b)];
    return (ia < 0 ? 99 : ia) - (ib < 0 ? 99 : ib) || a.localeCompare(b);
  });
  return ids.map((id) => ({
    id,
    title: config.groups?.[id]?.title ?? id[0].toUpperCase() + id.slice(1),
    description: config.groups?.[id]?.description ?? '',
    skills: skills.filter((s) => (s.metadata?.group ?? 'other') === id),
  }));
}

const firstSentence = (text) => String(text ?? '').split(/(?<=\.)\s/)[0].replace(/\|/g, '\\|');

function skillsTable(skills, config) {
  return groupsOf(skills, config)
    .map((g) => {
      const rows = g.skills.map((s) => `| [\`${s.name}\`](.agents/skills/${s.name}/SKILL.md) | ${firstSentence(s.description)} | ${s['disable-model-invocation'] === true ? 'you' : 'you or the model'} |`);
      return [`### ${g.title}`, '', ...(g.description ? [g.description, ''] : []), '| Skill | What it does | Started by |', '| --- | --- | --- |', ...rows].join('\n');
    })
    .join('\n\n');
}

function docsMap(root, config) {
  const dir = config.docs.conventions;
  if (!isDir(join(root, dir))) return '';
  return walk(join(root, dir))
    .filter((f) => f.endsWith('.md') && !/(^|\/)README\.md$/i.test(f))
    .sort()
    .map((f) => {
      const h1 = /^#\s+(.*)$/m.exec(read(join(root, dir, f)))?.[1] ?? f;
      return `- \`${dir}/${f}\`: ${h1.replace(/[^\p{L}\p{N}\p{P}\p{Zs}]/gu, '').trim()}`;
    })
    .join('\n');
}

function replaceBlock(text, id, content) {
  const re = new RegExp(`(<!-- harness:${id}:start -->)[\\s\\S]*?(<!-- harness:${id}:end -->)`);
  return re.test(text) ? text.replace(re, (_, a, b) => `${a}\n${content}\n${b}`) : null;
}

// ------------------------------------------------------------------ plan / diff / apply

export function planSync(root) {
  const { config } = loadConfig(root);
  const agents = new Set(config.agents);
  const notes = [];
  const files = [];
  const mirrors = [];
  const file = (path, content) => files.push({ path, content });
  const skills = loadSkillMeta(root);
  const ignored = (p) => Boolean(matchAny(p, config.ignore) || matchAny(`${p}/`, config.ignore));

  if (agents.has('claude')) {
    const settings = readJson(join(root, '.claude', 'settings.json'), notes);
    file('.claude/settings.json', json({ ...settings, hooks: mergeHooks(settings.hooks, claudeHooks(config)) }));
    mirrors.push({ path: '.claude/skills', source: '.agents/skills' });
    // Claude Code reads CLAUDE.md; an import keeps AGENTS.md the single source on every OS.
    for (const f of walk(root, { ignore: ignored }).filter((p) => /(^|\/)AGENTS\.md$/.test(p) && !p.startsWith('.agents/'))) {
      const target = f.replace(/AGENTS\.md$/, 'CLAUDE.md');
      const abs = join(root, target);
      if (existsSync(abs) && !read(abs).includes(GENERATED_NOTE)) {
        if (!/^@AGENTS\.md\s*$/m.test(read(abs))) notes.push(`${target}: exists and does not import AGENTS.md. Add a line "@AGENTS.md" so Claude Code reads the shared rules.`);
        continue;
      }
      file(target, `<!-- ${GENERATED_NOTE} -->\n@AGENTS.md\n`);
    }
  }
  if ((agents.has('claude') || agents.has('cursor')) && isDir(join(root, '.agents', 'agents'))) {
    mirrors.push({ path: '.claude/agents', source: '.agents/agents' });
  }
  if (agents.has('cursor')) {
    const existing = readJson(join(root, '.cursor', 'hooks.json'), notes);
    file('.cursor/hooks.json', json({ ...existing, version: 1, hooks: mergeHooks(existing.hooks, cursorHooks(config)) }));
  }
  if (agents.has('copilot')) {
    file('.github/hooks/harness.json', json({ version: 1, hooks: copilotHooks(config) }));
  }
  if (agents.has('codex')) {
    const existing = readJson(join(root, '.codex', 'hooks.json'), notes);
    file('.codex/hooks.json', json({ ...existing, hooks: mergeHooks(existing.hooks, codexHooks(config)) }));
  }
  if (agents.has('gemini')) {
    const existing = readJson(join(root, '.gemini', 'settings.json'), notes);
    const names = new Set([...[existing.context?.fileName ?? []].flat(), 'AGENTS.md', 'GEMINI.md']);
    file('.gemini/settings.json', json({ ...existing, context: { ...existing.context, fileName: [...names] }, hooks: mergeHooks(existing.hooks, geminiHooks(config)) }));
  }
  if (agents.has('opencode')) file('.opencode/plugins/harness-guard.js', OPENCODE_PLUGIN);

  // Distribution manifests, only where the project already has them.
  const pluginFile = join(root, '.claude-plugin', 'plugin.json');
  if (existsSync(pluginFile)) {
    const plugin = readJson(pluginFile, notes);
    const agentFiles = isDir(join(root, '.agents', 'agents')) ? readdirSync(join(root, '.agents', 'agents')).filter((n) => n.endsWith('.md')).sort().map((n) => `./.agents/agents/${n}`) : [];
    const guard = claudeHooks({ sensors: {} }, '${CLAUDE_PLUGIN_ROOT}').PreToolUse;
    file('.claude-plugin/plugin.json', json({ ...plugin, skills: './.agents/skills', ...(agentFiles.length ? { agents: agentFiles } : {}), hooks: { PreToolUse: guard } }));
  }
  if (existsSync(join(root, 'skills.sh.json'))) {
    const groupings = groupsOf(skills, config).map((g) => ({ title: g.title, ...(g.description ? { description: g.description } : {}), skills: g.skills.map((s) => s.name) }));
    file('skills.sh.json', json({ $schema: 'https://skills.sh/schemas/skills.sh.schema.json', notGrouped: 'bottom', groupings }));
  }

  // Marked blocks inside hand-written documents.
  for (const [path, id, content] of [
    ['README.md', 'skills', skillsTable(skills, config)],
    ['AGENTS.md', 'docs', docsMap(root, config)],
  ]) {
    const abs = join(root, path);
    if (!existsSync(abs)) continue;
    const next = replaceBlock(read(abs), id, content);
    if (next !== null) file(path, next);
  }

  return { files, mirrors, notes, mode: config.sync.mode };
}

function mirrorState(root, m) {
  const dest = join(root, m.path);
  const src = join(root, m.source);
  let st;
  try {
    st = lstatSync(dest);
  } catch {
    return 'missing';
  }
  if (st.isSymbolicLink()) {
    try {
      return realpathSync(dest) === realpathSync(src) ? 'ok' : 'stale';
    } catch {
      return 'stale';
    }
  }
  if (!st.isDirectory()) return 'placeholder'; // a symlink checked out as a text file on Windows
  if (!existsSync(join(dest, MARKER))) return 'foreign';
  const a = walk(src).sort();
  const b = walk(dest).filter((f) => f !== MARKER).sort();
  if (a.length !== b.length || a.some((f, i) => f !== b[i])) return 'stale';
  return a.every((f) => read(join(src, f)) === read(join(dest, f))) ? 'ok' : 'stale';
}

export function diffSync(root, plan) {
  const out = [];
  for (const f of plan.files) {
    const abs = join(root, f.path);
    if (!existsSync(abs)) out.push({ path: f.path, problem: 'Generated file is missing.' });
    else if (read(abs) !== f.content.replace(/\r\n/g, '\n')) out.push({ path: f.path, problem: 'Generated file is out of date.' });
  }
  for (const m of plan.mirrors) {
    const state = mirrorState(root, m);
    if (state === 'ok') continue;
    const problem = {
      missing: `Mirror of ${m.source} is missing.`,
      stale: `Mirror of ${m.source} is out of date.`,
      placeholder: `Expected a folder mirroring ${m.source}, found a file (a symlink that git checked out as text).`,
      foreign: `Folder exists but was not created by the harness. Move its contents into ${m.source} and delete it.`,
    }[state];
    out.push({ path: m.path, problem, mirror: true, state });
  }
  return out;
}

function writeMirror(root, m, mode) {
  const dest = join(root, m.path);
  const src = join(root, m.source);
  const state = mirrorState(root, m);
  if (state === 'ok') return null;
  if (state === 'foreign') return `skipped ${m.path}: it exists and is not managed by the harness`;
  if (state !== 'missing') {
    if (lstatSync(dest).isDirectory()) rmSync(dest, { recursive: true, force: true });
    else unlinkSync(dest);
  }
  mkdirSync(dirname(dest), { recursive: true });
  if (mode !== 'copy') {
    try {
      symlinkSync(relative(dirname(dest), src), dest, 'dir');
      return `linked ${m.path} -> ${m.source}`;
    } catch (e) {
      if (mode === 'symlink') return `failed ${m.path}: cannot create a symlink (${e.code}). On Windows enable Developer Mode, or set sync.mode to "copy".`;
    }
  }
  cpSync(src, dest, { recursive: true });
  writeFileSync(join(dest, MARKER), `Copied from ${m.source} by \`harness sync\`. Do not edit: changes here are overwritten.\n`);
  return `copied ${m.source} -> ${m.path}`;
}

export function applySync(root, plan, { mirrorsOnly = false } = {}) {
  const done = [];
  if (!mirrorsOnly) {
    for (const f of plan.files) {
      const abs = join(root, f.path);
      if (existsSync(abs) && read(abs) === f.content) continue;
      mkdirSync(dirname(abs), { recursive: true });
      writeFileSync(abs, f.content);
      done.push(`wrote ${f.path}`);
    }
  }
  for (const m of plan.mirrors) {
    const msg = writeMirror(root, m, plan.mode);
    if (msg) done.push(msg);
  }
  return done;
}
